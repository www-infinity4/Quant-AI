import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = file => readFileSync(resolve(root, file), 'utf8');
let packet = read('worker/src/packet.js');
let store = read('worker/src/store.js');
let entry = read('worker/src/index.js');
const personal=read('worker/src/personal.js').replace(/export (async )?function /g,(_,a)=>(a||'')+'function ');
const shopphi=read('worker/src/shopphi.js').replace(/export (async )?function /g,(_,a)=>(a||'')+'function ');
entry=entry.replace("import { personalProfile, assistListing } from './personal.js';\n",'');
entry=entry.replace("import { shopPhiOwned, shopPhiPublic } from './shopphi.js';\n",'');

const change = (source, oldText, newText, label) => {
 if (!source.includes(oldText)) throw Error('Missing source marker: ' + label);
 return source.replace(oldText, newText);
};
packet = packet.replace(/export function /g, 'function ');
store = change(store, "import { parsePacket, validWallet } from './packet.js';\n", '', 'packet import').replace(/export async function /g, 'async function ');
entry = change(entry, "import { ingestPacket, searchWithQuant, createFolder, listFolders, addFolderQuant, createInventoryExperiment } from './store.js';\n", '', 'store import')
 .replace('export const SYSTEM_PROMPT=', 'const SYSTEM_PROMPT=')
 .replace('export async function handle(', 'async function handle(');
entry = change(entry, "return env.ASSETS?env.ASSETS.fetch(request):json({error:'not_found'},404);", "return env.ASSETS?env.ASSETS.fetch(request):serveEmbeddedAsset(request);", 'static fallback');

const assets = {
 '/': ['text/html; charset=utf-8', read('public/index.html')],
 '/index.html': ['text/html; charset=utf-8', read('public/index.html')],
 '/app.js': ['application/javascript; charset=utf-8', read('public/app.js')],
 '/styles.css': ['text/css; charset=utf-8', read('public/styles.css')]
};
const embedded = `
const EMBEDDED_ASSETS=${JSON.stringify(assets)};
function serveEmbeddedAsset(request){
 const path=new URL(request.url).pathname;
 if(request.method!=='GET'&&request.method!=='HEAD')return new Response('Method not allowed',{status:405,headers:{'Allow':'GET, HEAD','Cache-Control':'no-store'}});
 const asset=Object.prototype.hasOwnProperty.call(EMBEDDED_ASSETS,path)?EMBEDDED_ASSETS[path]:null;
 if(!asset)return new Response('Not found',{status:404,headers:{'Cache-Control':'no-store'}});
 return new Response(request.method==='HEAD'?null:asset[1],{headers:{
  'Content-Type':asset[0],'Cache-Control':'no-store','X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer'
 }});
}
`;
const result = [
 '// Generated by scripts/build-edge.mjs; do not edit manually.',
 'const PacketModule=(()=>{', packet, 'return {parsePacket,validWallet};})();',
 'const StoreModule=(({parsePacket,validWallet})=>{', store,
 'return {ingestPacket,searchWithQuant,createFolder,listFolders,addFolderQuant,createInventoryExperiment};})(PacketModule);',
 'const {ingestPacket,searchWithQuant,createFolder,listFolders,addFolderQuant,createInventoryExperiment}=StoreModule;',
 embedded,
 personal,
 shopphi,
 entry
].join('\n');
mkdirSync(resolve(root,'dist'),{recursive:true});
writeFileSync(resolve(root,'dist/worker.mjs'),result,'utf8');
console.log('Built Quant-AI Worker with embedded same-origin assets ('+result.length+' bytes).');
